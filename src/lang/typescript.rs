//! TypeScript (`typescript-fetch` flavour): type mapping, naming and contexts.
//!
//! Options: `fileNaming` (`kebab-case` only), plus the template flags
//! `withoutRuntimeChecks`, `stringEnums`, `importFileExtension`.

use super::{Contexts, Language, common_enum_prefix, java_hash_set_order, opt_bool, opt_str};
use crate::core::{EnumDef, Model, ModelKind, Operation, ParamIn, Prop, Spec, Ty, TyKind};
use crate::naming::{camelize, enum_var_name, kebab};
use serde_json::{Map, Value, json};
use std::collections::BTreeMap;
use std::collections::BTreeSet;

pub struct TypeScript {
    options: Map<String, Value>,
}

impl TypeScript {
    pub fn new(options: Map<String, Value>) -> Result<Self, String> {
        let naming = opt_str(&options, "fileNaming", "kebab-case");
        if naming != "kebab-case" {
            return Err(format!(
                "typescript: fileNaming '{naming}' is not supported (only kebab-case)"
            ));
        }
        Ok(TypeScript { options })
    }
}

/// A core type mapped to TypeScript.
struct TsType {
    datatype: String,
    primitive: bool,
    items: Option<Box<TsType>>,
    ty: Ty,
}

impl TsType {
    fn of(t: &Ty) -> TsType {
        let (datatype, primitive, items) = match &t.kind {
            TyKind::String if t.is_date() || t.is_date_time() => ("Date".to_string(), true, None),
            TyKind::String if t.is_binary() => ("Blob".to_string(), true, None),
            TyKind::String => ("string".to_string(), true, None),
            TyKind::Integer | TyKind::Number => ("number".to_string(), true, None),
            TyKind::Boolean => ("boolean".to_string(), true, None),
            TyKind::Array(inner) => {
                let i = TsType::of(inner);
                let name = format!("{}<{}>", if t.unique { "Set" } else { "Array" }, i.datatype);
                (name, i.primitive, Some(Box::new(i)))
            }
            TyKind::Map(inner) => {
                let i = TsType::of(inner);
                (
                    format!("{{ [key: string]: {}; }}", i.datatype),
                    i.primitive,
                    Some(Box::new(i)),
                )
            }
            TyKind::Ref(name) => (name.clone(), false, None),
            TyKind::Object => ("object".to_string(), false, None),
            TyKind::Any => ("any".to_string(), false, None),
        };
        TsType {
            datatype,
            primitive,
            items,
            ty: t.clone(),
        }
    }

    /// Coarse category used by the Jinja templates instead of the many is* flags.
    fn kind(&self) -> &'static str {
        let t = &self.ty;
        if t.is_date() {
            "date"
        } else if t.is_date_time() {
            "datetime"
        } else if t.is_array() && t.unique {
            "set"
        } else if t.is_array() {
            "array"
        } else if t.is_map() {
            "map"
        } else if t.is_ref() {
            "ref"
        } else {
            "plain"
        }
    }

    fn items_json(&self) -> Value {
        match &self.items {
            Some(i) => {
                json!({ "datatype": i.datatype, "dataType": i.datatype, "primitive": i.primitive })
            }
            None => Value::Null,
        }
    }
}

impl Language for TypeScript {
    fn contexts(&self, spec: &Spec) -> Result<Contexts, String> {
        let info = &spec.root["info"];
        let global = json!({
            "appName": info["title"],
            "appDescription": info.get("description").cloned().unwrap_or_else(||
                json!("No description provided (generated by Openapi Generator https://github.com/openapitools/openapi-generator)")),
            "version": info["version"],
            "infoEmail": info.pointer("/contact/email"),
            "importFileExtension": opt_str(&self.options, "importFileExtension", ""),
            "withoutRuntimeChecks": opt_bool(&self.options, "withoutRuntimeChecks", false),
            "stringEnums": opt_bool(&self.options, "stringEnums", false),
            "useSingleRequestParameter": opt_bool(&self.options, "useSingleRequestParameter", true),
            "prefixParameterInterfaces": opt_bool(&self.options, "prefixParameterInterfaces", false),
            "withInterfaces": opt_bool(&self.options, "withInterfaces", false),
            "basePath": spec.root.pointer("/servers/0/url").and_then(Value::as_str).unwrap_or("http://localhost"),
            "useSquareBracketsInArrayNames": false,
            "useSagaAndRecords": false,
        });

        let names: Vec<&str> = spec
            .model_names()
            .into_iter()
            .filter(|n| !spec.form_only.contains(*n))
            .collect();
        let models = names
            .into_iter()
            .map(|name| json!({ "models": [{ "model": model(&spec.model(name)), "importPath": name }] }))
            .collect();
        let apis = apis(spec)?;
        let once = json!({});
        Ok(Contexts {
            global,
            models,
            apis,
            once,
        })
    }
}

fn model(m: &Model) -> Value {
    let description = m.description.unwrap_or("");
    let (props, discriminator) = match &m.kind {
        ModelKind::Enum(e) => {
            return json!({
                "classname": m.name,
                "classFilename": kebab(&m.name),
                "isEnum": true,
                "unescapedDescription": description,
                "description": description,
                "allowableValues": enum_vars(e),
            });
        }
        ModelKind::Object {
            props,
            discriminator,
        } => (props, discriminator),
    };

    let mut imports = BTreeSet::new();
    let mut has_enums = false;
    let mut vars = Vec::new();
    for p in props {
        if let Some(c) = p.ty.class_ref()
            && c != m.name
        {
            imports.insert(c.to_string());
        }
        has_enums |= p.ty.enum_ref || p.inline_enum.is_some();
        vars.push(property(&m.name, p));
    }
    let ts_imports: Vec<Value> = java_hash_set_order(imports.into_iter().collect())
        .iter()
        .map(|c| json!({ "classname": c, "filename": kebab(c) }))
        .collect();
    let discriminator = discriminator.as_ref().map(|d| {
        json!({
            "propertyName": camelize(&d.property, true),
            "propertyBaseName": d.property,
            "mappedModels": d.mapping.iter().map(|(k, m)| json!({ "mappingName": k, "modelName": m })).collect::<Vec<_>>(),
        })
    });
    json!({
        "classname": m.name,
        "classFilename": kebab(&m.name),
        "isEnum": false,
        "unescapedDescription": description,
        "description": description,
        "hasVars": !vars.is_empty(),
        "vars": vars,
        "hasEnums": has_enums,
        "hasImports": !ts_imports.is_empty(),
        "tsImports": ts_imports,
        "discriminator": discriminator,
        "parent": null,
        "additionalPropertiesType": null,
        "hasReadOnly": false,
        "readOnlyVars": [],
        "oneOf": [],
    })
}

fn property(classname: &str, p: &Prop) -> Value {
    let t = TsType::of(&p.ty);
    let description = p.description.unwrap_or("");
    let name = camelize(&p.base_name, true);
    // An inline enum is named <Class><Property>Enum, while `datatype` keeps the resolved type.
    let enum_name = format!("{}Enum", camelize(&name, false));
    let datatype_with_enum = if p.inline_enum.is_some() {
        format!("{classname}{enum_name}")
    } else {
        t.datatype.clone()
    };
    json!({
        "baseName": p.base_name,
        "name": name,
        "required": p.required,
        "isNullable": p.ty.nullable,
        "isReadOnly": p.read_only,
        "deprecated": p.deprecated,
        "description": description,
        "unescapedDescription": description,
        "datatype": t.datatype,
        "dataType": t.datatype,
        "datatypeWithEnum": datatype_with_enum,
        "isEnum": p.inline_enum.is_some(),
        "enumName": enum_name,
        "allowableValues": p.inline_enum.as_ref().map(enum_vars),
        "isEnumRef": p.ty.enum_ref,
        "isPrimitiveType": t.primitive,
        "isDateType": p.ty.is_date(),
        "isDateTimeType": p.ty.is_date_time(),
        "isArray": p.ty.is_array(),
        "isMap": p.ty.is_map(),
        "uniqueItems": p.ty.unique,
        "isFreeFormObject": p.ty.is_free_form(),
        "items": t.items_json(),
        "kind": t.kind(),
    })
}

fn enum_vars(e: &EnumDef) -> Value {
    let strs: Vec<&str> = e.values.iter().filter_map(Value::as_str).collect();
    let prefix_len = common_enum_prefix(&strs).len();
    let vars: Vec<Value> = strs
        .iter()
        .map(|v| {
            let short = if v.len() > prefix_len { &v[prefix_len..] } else { v };
            json!({ "name": enum_var_name(short), "value": format!("'{}'", v.replace('\'', "\\'")) })
        })
        .collect();
    json!({ "enumVars": vars })
}

/// openapi-generator's `sanitizeTag`: "Admin/Instance/Logo" -> "AdminInstanceLogo".
pub fn sanitize_tag(tag: &str) -> String {
    let cleaned: String = tag
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '_' })
        .collect();
    camelize(&cleaned, false)
}

/// One context per tag, sorted by sanitized tag name.
fn apis(spec: &Spec) -> Result<Vec<Value>, String> {
    let mut by_tag: BTreeMap<String, Vec<Value>> = BTreeMap::new();
    for op in spec.operations()? {
        by_tag
            .entry(sanitize_tag(&op.tag))
            .or_default()
            .push(operation(spec, &op)?);
    }
    let mut out = Vec::new();
    for (tag, mut ops) in by_tag {
        let classname = format!("{tag}Api");
        ops.sort_by(|a, b| a["nickname"].as_str().cmp(&b["nickname"].as_str()));
        let imports: BTreeSet<String> = ops
            .iter()
            .flat_map(|op| {
                op["imports"]
                    .as_array()
                    .unwrap()
                    .iter()
                    .map(|i| i.as_str().unwrap().to_string())
            })
            .collect();
        let imports: Vec<Value> = imports
            .iter()
            .map(|c| json!({ "import": format!("models.{c}"), "classname": c, "className": c }))
            .collect();
        let has_enums = ops.iter().any(|o| {
            o["allParams"]
                .as_array()
                .unwrap()
                .iter()
                .any(|p| p["isEnum"] == true)
        });
        out.push(json!({
            "classname": classname,
            "baseName": tag,
            "hasEnums": has_enums,
            "classFilename": kebab(&classname),
            "imports": imports,
            "operations": { "classname": classname, "description": "", "operation": ops },
        }));
    }
    Ok(out)
}

fn operation(spec: &Spec, op: &Operation) -> Result<Value, String> {
    let nickname = camelize(&op.id, true);
    let mut op_camel = camelize(&op.id, false);
    // The request interface must not clash with a model of the same name.
    if spec.schemas.contains_key(&format!("{op_camel}Request")) {
        op_camel.push_str("Operation");
    }

    let mut imports = BTreeSet::new();
    let mut params = Vec::new();
    let mut body = Value::Null;
    for p in &op.params {
        if let Some(c) = p.ty.class_ref() {
            imports.insert(c.to_string());
        }
        let t = TsType::of(&p.ty);
        let name = if p.location == ParamIn::Body {
            camelize(&p.name, true)
        } else {
            p.name.clone()
        };
        let mut v = param(&name, &t, p.required);
        v["description"] = json!(p.description);
        if matches!(p.location, ParamIn::Query) && p.ty.is_array() {
            v["collectionFormat"] = json!(if p.explode { "multi" } else { "csv" });
            v["isCollectionFormatMulti"] = json!(p.explode);
        }
        v["in"] = json!(match p.location {
            ParamIn::Path => "path",
            ParamIn::Query => "query",
            ParamIn::Header => "header",
            ParamIn::Cookie => "cookie",
            ParamIn::Form => "form",
            ParamIn::Body => "body",
        });
        if matches!(
            p.location,
            ParamIn::Path | ParamIn::Query | ParamIn::Header | ParamIn::Cookie
        ) {
            v["collectionMulti"] = json!(p.explode);
        }
        if p.location == ParamIn::Body {
            body = v.clone();
        }
        params.push(v);
    }
    // Per-location lists keep declaration order; allParams puts required ones first.
    let by_location =
        |loc: &str| -> Vec<Value> { params.iter().filter(|p| p["in"] == loc).cloned().collect() };
    let (path_params, query_params, header_params, form_params) = (
        by_location("path"),
        by_location("query"),
        by_location("header"),
        by_location("form"),
    );
    params.sort_by_key(|p| !p["required"].as_bool().unwrap());

    let success: Vec<Value> = op
        .responses
        .iter()
        .filter(|r| r.code.starts_with('2'))
        .map(|r| json!({ "code": r.code.parse::<u16>().unwrap_or(200), "hasData": r.raw.get("content").is_some() }))
        .collect();
    let lowest = op
        .responses
        .iter()
        .filter(|r| r.code.starts_with('2'))
        .min_by_key(|r| r.code.clone());
    let ret = lowest
        .and_then(|r| r.content.as_ref())
        .map(|(_, t, _)| TsType::of(t));
    if let Some(c) = ret.as_ref().and_then(|t| t.ty.class_ref()) {
        imports.insert(c.to_string());
    }
    let response_optional = ret.is_some() && success.iter().any(|r| r["hasData"] == false);

    let mut auth = Vec::new();
    for s in &op.security {
        if s.scheme["type"] != "http" || s.scheme["scheme"] != "bearer" {
            return Err(format!(
                "security scheme {}: only http bearer is supported",
                s.name
            ));
        }
        let scopes: Vec<Value> = s
            .scopes
            .as_array()
            .into_iter()
            .flatten()
            .map(|sc| json!({ "scope": sc }))
            .collect();
        auth.push(json!({
            "name": s.name,
            "description": s.scheme.get("description"),
            "isBasic": true,
            "isBasicBearer": true,
            "scopes": scopes,
        }));
    }

    Ok(json!({
        "nickname": nickname,
        "operationId": op.id,
        "operationIdCamelCase": op_camel,
        "isArray": ret.as_ref().is_some_and(|t| t.ty.is_array()),
        "summary": op.summary,
        "notes": op.description,
        "isDeprecated": op.deprecated,
        "httpMethod": op.method.to_uppercase(),
        "path": op.path,
        "hasRequiredParams": params.iter().any(|p| p["required"] == true),
        "allParams": params,
        "pathParams": path_params,
        "queryParams": query_params,
        "headerParams": header_params,
        "formParams": form_params,
        "bodyParam": body,
        "consumes": op.consumes.iter().map(|m| json!({ "mediaType": m })).collect::<Vec<_>>(),
        "hasBodyParam": !body.is_null(),
        "hasFormParams": !form_params.is_empty(),
        "returnType": ret.as_ref().map(|t| t.datatype.clone()),
        "returnBaseType": ret.as_ref().map(|t| t.items.as_ref().map_or(t.datatype.clone(), |i| i.datatype.clone())),
        "returnSimpleType": ret.as_ref().is_some_and(|t| t.items.is_none()),
        "returnTypeIsPrimitive": ret.as_ref().is_some_and(|t| t.primitive || t.ty.kind == TyKind::Any),
        "isResponseFile": ret.as_ref().is_some_and(|t| t.datatype == "Blob"),
        "responses": op.responses.iter().map(|r| {
            let t = r.content.as_ref().map(|(_, t, _)| TsType::of(t));
            json!({
                "code": r.code,
                "is2xx": r.code.starts_with('2'),
                "message": r.description,
                "dataType": t.as_ref().map(|t| t.datatype.clone()),
                "isPrimitiveType": t.as_ref().is_none_or(|t| t.primitive),
            })
        }).collect::<Vec<_>>(),
        "returns": ret.as_ref().map(returns),
        "isResponseOptional": response_optional,
        "successResponses": success,
        "authMethods": auth,
        "imports": imports,
    }))
}

fn param(name: &str, t: &TsType, required: bool) -> Value {
    json!({
        "baseName": name,
        "paramName": camelize(name, true),
        "required": required,
        "dataType": t.datatype,
        "datatypeWithEnum": t.datatype,
        "isNullable": t.ty.nullable,
        "kind": t.kind(),
        "isPrimitive": t.primitive,
        "isPrimitiveType": t.primitive && t.items.is_none(),
        "isArray": t.ty.is_array(),
        "isMap": t.ty.is_map(),
        "isContainer": t.items.is_some(),
        "uniqueItems": t.ty.unique,
        "isDateType": t.ty.is_date(),
        "isDateTimeType": t.ty.is_date_time(),
        "isEnumRef": t.ty.enum_ref,
        "isFile": t.datatype == "Blob",
        "items": t.items.as_ref().map(|i| json!({
            "datatype": i.datatype,
            "dataType": i.datatype,
            "datatypeWithEnum": i.datatype,
            "primitive": i.primitive,
            "isPrimitiveType": i.primitive,
            "isDateType": i.ty.is_date(),
            "isDateTimeType": i.ty.is_date_time(),
            "isEnumRef": i.ty.enum_ref,
        })),
    })
}

/// How the raw response is turned into a value.
fn returns(t: &TsType) -> Value {
    let kind = if t.datatype == "Blob" {
        "blob"
    } else if t.primitive || t.ty.is_free_form() {
        match t.kind() {
            "array" | "set" | "map" => "json-any",
            _ => "json-or-text",
        }
    } else {
        match t.kind() {
            "array" => "model-array",
            "set" => "model-set",
            "map" => "model-map",
            _ => "model",
        }
    };
    let base = t
        .items
        .as_ref()
        .map(|i| i.datatype.clone())
        .unwrap_or_else(|| t.datatype.clone());
    json!({ "kind": kind, "baseType": base })
}
